package server

import "net/http"

func (s *Server) Handler() http.Handler {
	mux := http.NewServeMux()

	// Trusted, same-origin JSON API (token-gated where noted).
	mux.HandleFunc("POST /api/upload", s.rateLimit(s.uploadLimiter, s.authToken(s.handleUpload)))
	mux.HandleFunc("GET /api/uploads", s.authToken(s.handleListUploads))
	mux.HandleFunc("DELETE /api/uploads/{slug}", s.authToken(s.handleDeleteUpload))
	mux.HandleFunc("POST /api/uploads/{slug}/visibility", s.authToken(s.handleSetVisibility))
	mux.HandleFunc("POST /api/uploads/{slug}/name", s.authToken(s.handleRenameUpload))
	mux.HandleFunc("GET /api/uploads/{slug}/stats", s.authToken(s.handleStats))
	mux.HandleFunc("POST /api/uploads/{slug}/account-comments", s.authToken(s.handleAddAccountComment))
	mux.HandleFunc("POST /api/tokens", s.authAdmin(s.handleCreateToken))
	mux.HandleFunc("GET /api/tokens", s.authAdmin(s.handleListTokens))
	mux.HandleFunc("DELETE /api/tokens/{id}", s.authAdmin(s.handleDeleteToken))
	mux.HandleFunc("POST /api/provisioners", s.authAdmin(s.handleCreateProvisioner))
	mux.HandleFunc("GET /api/provisioners", s.authAdmin(s.handleListProvisioners))
	mux.HandleFunc("DELETE /api/provisioners/{id}", s.authAdmin(s.handleDeleteProvisioner))
	mux.HandleFunc("GET /api/provisioning/self", s.authProvisioner(s.handleProvisioningSelf))
	mux.HandleFunc("PUT /api/provisioning/accounts/{external_id}", s.authProvisioner(s.handleProvisioningUpsert))
	mux.HandleFunc("POST /api/provisioning/accounts/{external_id}/token", s.authProvisioner(s.handleProvisioningToken))
	mux.HandleFunc("DELETE /api/provisioning/accounts/{external_id}", s.authProvisioner(s.handleProvisioningRelease))
	mux.HandleFunc("GET /api/settings", s.authAdmin(s.handleGetSettings))
	mux.HandleFunc("PUT /api/settings", s.authAdmin(s.handleUpdateSettings))
	mux.HandleFunc("GET /api/audit", s.authAdmin(s.handleAuditLog))
	mux.HandleFunc("GET /api/uploads/{slug}/versions", s.authToken(s.handleListVersions))
	mux.HandleFunc("GET /api/uploads/{slug}/export", s.authToken(s.handleExportUpload))
	mux.HandleFunc("GET /api/uploads/{slug}/grants", s.authToken(s.handleListGrants))
	mux.HandleFunc("POST /api/uploads/{slug}/grants", s.authToken(s.handleAddGrant))
	mux.HandleFunc("DELETE /api/uploads/{slug}/grants", s.authToken(s.handleRemoveGrant))
	mux.HandleFunc("GET /api/uploads/{slug}/backend", s.authToken(s.handleGetBackend))
	mux.HandleFunc("PUT /api/uploads/{slug}/versions/{n}/backend", s.authToken(s.handleSetBackend))
	mux.HandleFunc("DELETE /api/uploads/{slug}/versions/{n}/backend", s.authToken(s.handleRemoveBackend))
	mux.HandleFunc("GET /api/uploads/{slug}/versions/{n}/backend/logs", s.authToken(s.handleBackendLogs))
	mux.HandleFunc("PUT /api/uploads/{slug}/backend/env/{name}", s.authToken(s.handleSetBackendEnv))
	mux.HandleFunc("DELETE /api/uploads/{slug}/backend/env/{name}", s.authToken(s.handleUnsetBackendEnv))
	mux.HandleFunc("POST /api/uploads/{slug}/backend/restart", s.authToken(s.handleRestartBackend))
	mux.HandleFunc("PUT /api/uploads/{slug}/backend/token-calls", s.authToken(s.handleSetBackendTokenCalls))
	mux.HandleFunc("GET /api/uploads/{slug}/backend/data", s.authToken(s.handleExportBackendData))
	mux.HandleFunc("PUT /api/uploads/{slug}/backend/data", s.authToken(s.handleImportBackendData))
	mux.HandleFunc("GET /api/uploads/{slug}/versions/{n}/svc/{path...}", s.authToken(s.handleBackendTokenCall))
	mux.HandleFunc("POST /api/uploads/{slug}/versions/{n}/svc/{path...}", s.authToken(s.handleBackendTokenCall))
	mux.HandleFunc("PUT /api/uploads/{slug}/versions/{n}/svc/{path...}", s.authToken(s.handleBackendTokenCall))
	mux.HandleFunc("PATCH /api/uploads/{slug}/versions/{n}/svc/{path...}", s.authToken(s.handleBackendTokenCall))
	mux.HandleFunc("DELETE /api/uploads/{slug}/versions/{n}/svc/{path...}", s.authToken(s.handleBackendTokenCall))
	mux.HandleFunc("DELETE /api/uploads-by-owner", s.authToken(s.handleDeleteAllByOwner))
	mux.HandleFunc("GET /api/auth/providers", s.handleAuthProviders)
	mux.HandleFunc("POST /api/cli/login/start", s.rateLimit(s.cliLoginLimiter, s.handleCLILoginStart))
	mux.HandleFunc("POST /api/cli/login/poll", s.rateLimit(s.cliLoginLimiter, s.handleCLILoginPoll))

	// Page-side API (callable by the trusted parent page JS).
	mux.HandleFunc("GET /api/uploads/{slug}/comments", s.handleListComments)
	mux.HandleFunc("POST /api/uploads/{slug}/comments", s.handleAddComment)
	mux.HandleFunc("GET /api/uploads/{slug}/views", s.handleViews)
	mux.HandleFunc("GET /api/uploads/{slug}/events", s.handlePageEvents)
	mux.HandleFunc("GET /svc/{slug}/v/{n}/{path...}", s.handleBackendProxy)
	mux.HandleFunc("POST /svc/{slug}/v/{n}/{path...}", s.handleBackendProxy)
	mux.HandleFunc("PUT /svc/{slug}/v/{n}/{path...}", s.handleBackendProxy)
	mux.HandleFunc("PATCH /svc/{slug}/v/{n}/{path...}", s.handleBackendProxy)
	mux.HandleFunc("DELETE /svc/{slug}/v/{n}/{path...}", s.handleBackendProxy)

	// Pages & assets.
	mux.HandleFunc("GET /p/{slug}", s.handlePage)
	mux.HandleFunc("GET /p/{slug}/v/{n}", s.handlePageVersion)
	mux.HandleFunc("GET /p/{slug}/icon", s.handlePageIcon)
	mux.HandleFunc("GET /p/{slug}/manifest.webmanifest", s.handlePageManifest)
	mux.HandleFunc("GET /raw/{slug}/v/{n}", s.handleRawVersion)
	mux.HandleFunc("GET /bridge.js", s.handleBridge)
	mux.HandleFunc("GET /app.js", s.handleApp)
	mux.HandleFunc("GET /dashboard-alpine.js", s.handleDashboardAlpine)
	mux.HandleFunc("GET /toast.js", s.handleToast)
	mux.HandleFunc("GET /alpine.min.js", s.handleAlpine)
	mux.HandleFunc("GET /pines.css", s.handlePines)
	mux.HandleFunc("GET /favicon.svg", s.handleFaviconSVG)
	mux.HandleFunc("GET /favicon.png", s.handleFaviconPNG)
	mux.HandleFunc("GET /favicon.ico", s.handleFaviconICO)
	mux.HandleFunc("GET /logo.svg", s.handleLogoSVG)
	mux.HandleFunc("GET /logo.png", s.handleLogoPNG)
	mux.HandleFunc("GET /", s.handleIndex)

	// Health checks (unauthenticated, for load balancers / orchestrators).
	mux.HandleFunc("GET /healthz", s.handleHealthz)
	mux.HandleFunc("GET /readyz", s.handleReadyz)

	// Prometheus metrics (metrics token or admin API token).
	mux.HandleFunc("GET /metrics", s.handleMetrics)

	// Web GUI (browser-based management).
	mux.HandleFunc("GET /setup", s.handleSetup)
	mux.HandleFunc("POST /setup", s.rateLimit(s.loginLimiter, s.handleSetup))
	mux.HandleFunc("GET /login", s.handleLogin)
	mux.HandleFunc("POST /login", s.rateLimit(s.loginLimiter, s.handleLogin))
	mux.HandleFunc("GET /oauth/{provider}/start", s.rateLimit(s.loginLimiter, s.handleOAuthStart))
	mux.HandleFunc("GET /oauth/{provider}/callback", s.rateLimit(s.loginLimiter, s.handleOAuthCallback))
	mux.HandleFunc("GET /invite/{token}", s.handleInviteLink)
	mux.HandleFunc("GET /cli-login", s.handleCLILoginEntry)
	mux.HandleFunc("POST /cli-login", s.rateLimit(s.loginLimiter, s.handleCLILoginLookup))
	mux.HandleFunc("GET /cli-login/{code}", s.handleCLILoginLegacyLink)
	mux.HandleFunc("POST /cli-login/{code}", s.rateLimit(s.loginLimiter, s.handleCLILoginApprove))
	mux.HandleFunc("POST /logout", s.handleLogout)
	mux.HandleFunc("GET /dashboard", s.handleDashboard)
	mux.HandleFunc("GET /admin", s.handleAdmin)
	mux.HandleFunc("POST /dashboard/upload", s.handleDashboardUpload)
	mux.HandleFunc("POST /dashboard/delete/{slug}", s.handleDashboardDelete)
	mux.HandleFunc("POST /dashboard/visibility/{slug}", s.handleDashboardVisibility)
	mux.HandleFunc("POST /dashboard/grants/{slug}", s.handleDashboardGrantAdd)
	mux.HandleFunc("POST /dashboard/grants/{slug}/remove", s.handleDashboardGrantRemove)
	mux.HandleFunc("POST /dashboard/rename/{slug}", s.handleDashboardRename)
	mux.HandleFunc("POST /dashboard/api-keys", s.handleDashboardAPIKeyCreate)
	mux.HandleFunc("POST /dashboard/api-keys/{id}/regenerate", s.handleDashboardAPIKeyRegenerate)
	mux.HandleFunc("POST /dashboard/api-keys/{id}/revoke", s.handleDashboardAPIKeyRevoke)
	mux.HandleFunc("POST /dashboard/sessions/revoke", s.handleDashboardSessionsRevoke)
	mux.HandleFunc("POST /dashboard/settings", s.handleDashboardSettings)
	mux.HandleFunc("POST /dashboard/email/test", s.handleDashboardEmailTest)
	mux.HandleFunc("POST /dashboard/invites", s.handleDashboardCreateInvite)
	mux.HandleFunc("POST /dashboard/invites/revoke/{id}", s.handleDashboardRevokeInvite)
	mux.HandleFunc("POST /dashboard/users/{id}/admin", s.handleDashboardUserAdmin)
	mux.HandleFunc("POST /dashboard/users/{id}/disabled", s.handleDashboardUserDisabled)
	mux.HandleFunc("POST /dashboard/provisioners/{id}/revoke", s.handleDashboardProvisionerRevoke)
	mux.HandleFunc("GET /dashboard/stats/{slug}", s.handleDashboardStats)

	return s.withMiddleware(mux)
}
